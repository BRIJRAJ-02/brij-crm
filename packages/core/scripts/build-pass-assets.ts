// Turns the pass images in `src/profile/pass-assets/` into `src/profile/pass-images.ts`, where they travel as
// base64 in the source. A Vercel Function is a traced bundle, and a PNG read off disk at run time is exactly the
// kind of file tracing misses, so the bytes go in the module rather than beside it.
//
//   node packages/core/scripts/build-pass-assets.ts            writes the file
//   node packages/core/scripts/build-pass-assets.ts --check    fails when it is stale (CI, `pnpm check`)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, '..', 'src', 'profile', 'pass-assets');
const target = join(here, '..', 'src', 'profile', 'pass-images.ts');

const names = readdirSync(assets)
  .filter((name) => name.endsWith('.png'))
  .sort();

const lines = names.map((name) => {
  const base64 = readFileSync(join(assets, name)).toString('base64');
  return `  '${name}': '${base64}',`;
});

const source = `// Generated by \`node packages/core/scripts/build-pass-assets.ts\` from \`src/profile/pass-assets/\`.
// Never edited by hand: change the PNG, run the script, commit both.
/* eslint-disable */

/** The Timefix images every Wallet pass carries, base64 as they are in \`pass-assets/\`. */
const ENCODED: Readonly<Record<string, string>> = {
${lines.join('\n')}
};

/** One of the pass images as bytes. Decoded once per name, on first use. */
const decoded = new Map<string, Uint8Array>();

/** The named pass image, or a refusal: a missing image means the generated file and the caller drifted apart. */
export function passImage(name: string): Uint8Array {
  const already = decoded.get(name);
  if (already !== undefined) return already;
  const base64 = ENCODED[name];
  if (base64 === undefined) throw new Error(\`pass: there is no image called \${name}\`);
  const bytes = new Uint8Array(Buffer.from(base64, 'base64'));
  decoded.set(name, bytes);
  return bytes;
}

/** Every image this file carries, by name. */
export const PASS_IMAGE_NAMES: readonly string[] = Object.keys(ENCODED);
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== source) {
    console.error('PASS_IMAGES_STALE: run `node packages/core/scripts/build-pass-assets.ts` and commit the result.');
    process.exit(1);
  }
  console.log('pass images are current');
} else {
  writeFileSync(target, source);
  console.log(`wrote ${String(names.length)} images to pass-images.ts`);
}
