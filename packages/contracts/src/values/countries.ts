/** One country code from `COUNTRY_CODES`. */
export type CountryCode = (typeof COUNTRY_CODES)[number];

const COUNTRIES: ReadonlySet<string> = new Set(COUNTRY_CODES);

/** Codes people commonly write that ISO spells differently. */
const COUNTRY_ALIASES: Readonly<Record<string, CountryCode>> = { UK: 'GB' };

/** True for a code in `COUNTRY_CODES`. */
export function isCountryCode(code: string): code is CountryCode {
  return COUNTRIES.has(code);
}

/**
 * Reads a country code from text an import or a paste brings: trimmed, upper
 * cased, with `UK` read as `GB`. `undefined` for anything not in the list.
 */
export function countryCodeFromText(text: string): CountryCode | undefined {
  const code = text.trim().toUpperCase();
  const known = COUNTRY_ALIASES[code] ?? code;
  return isCountryCode(known) ? known : undefined;
}
